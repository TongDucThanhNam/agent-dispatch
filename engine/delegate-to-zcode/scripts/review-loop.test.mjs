  fs.unlinkSync(path.join(project, 'src', 'app.js'));
  const third = await computeSourceState(config);
  const drift = diffSourceStates(after, third);
  assert.deepEqual(drift.added, ['src/new.js']);
  assert.deepEqual(drift.removed, ['src/app.js']);
  const unavailable = diffSourceStates({ kind: 'none' }, third);
  assert.equal(unavailable.comparable, false);
