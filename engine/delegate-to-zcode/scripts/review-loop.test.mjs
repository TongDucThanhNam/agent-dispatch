test('Git identity detects content changes to already dirty and untracked files in a nested project', async t => {
  const git = await spawnCaptured('git', ['--version'], { timeoutMs: 10_000 });
  if (!git.ok) t.skip('git is not available');
  const project = makeProject(t, 'gitid');
  await spawnCaptured('git', ['-C', project, 'init'], { timeoutMs: 20_000 });
  await spawnCaptured('git', ['-C', project, 'config', 'user.email', 'fixture@example.com'], { timeoutMs: 10_000 });
  await spawnCaptured('git', ['-C', project, 'config', 'user.name', 'Fixture'], { timeoutMs: 10_000 });
  await spawnCaptured('git', ['-C', project, 'add', 'src/app.js'], { timeoutMs: 10_000 });
  await spawnCaptured('git', ['-C', project, 'commit', '-m', 'base'], { timeoutMs: 20_000 });
  const config = { project };
  assert.equal(detectSourceScope(config).kind, 'git');
  const before = await computeSourceState(config);
  assert.equal(before.kind, 'git');
  assert.ok(before.head);
  const untracked = path.join(project, 'src', 'untracked.js');
  fs.writeFileSync(untracked, 'new source file');
  const after = await computeSourceState(config);
  assert.equal(diffSourceStates(before, after).identical, false);
  assert.ok(diffSourceStates(before, after).added.includes('src/untracked.js'));
  fs.writeFileSync(path.join(project, 'src', 'app.js'), 'dirty first');
  const dirty = await computeSourceState(config);
  fs.writeFileSync(path.join(project, 'src', 'app.js'), 'dirty second');
  fs.writeFileSync(untracked, 'changed untracked content');
  const changed = diffSourceStates(dirty, await computeSourceState(config));
  assert.equal(changed.identical, false);
  assert.deepEqual(changed.changed, ['src/app.js', 'src/untracked.js']);
  const nested = await computeSourceState({ project: path.join(project, 'src') });
  assert.equal(nested.kind, 'git');
  assert.ok(nested.files['app.js']);
});

