test('verdict parsing rejects malformed and contradictory acceptance', () => {
  const good = parseReviewVerdict(JSON.stringify(acceptedVerdict('Verified.')));
  assert.equal(good.verdict, 'accepted');
  const findings = changesVerdict('defect');
  assert.throws(() => parseReviewVerdict(JSON.stringify({ ...findings, verdict: 'accepted' })), /Accepted requires/);
  assert.throws(() => parseReviewVerdict(JSON.stringify({ ...acceptedVerdict('s'), checks: [{ name: 'test', result: 'fail', evidence: 'test.log' }] })), /Accepted requires/);
  assert.throws(() => parseReviewVerdict(JSON.stringify({ ...acceptedVerdict('s'), checks: [] })), /Accepted requires/);
  assert.throws(() => parseReviewVerdict(JSON.stringify({ ...acceptedVerdict('s'), surprise: true })), /schema/);
  assert.throws(() => parseReviewVerdict(JSON.stringify({ ...findings, findings: [{ ...findings.findings[0], severity: 'invalid' }] })), /severity/);
  assert.throws(() => parseReviewVerdict('```json\n' + JSON.stringify(good) + '\n```'), /not JSON/);
  assert.throws(() => parseReviewVerdict(''), /no final message/);
  assert.throws(() => parseReviewVerdict('not json'), /not JSON/);
  assert.throws(() => parseReviewVerdict('{"verdict":"ok"}'), /accepted, changes_required, needs_replan/);
  assert.throws(() => parseReviewVerdict('{"verdict":"accepted","findings":"many"}'), /findings array/);
  assert.throws(() => parseReviewVerdict('{"verdict":"accepted"}'), /findings array/);
  assert.throws(() => parseReviewVerdict('{"verdict":"accepted","findings":[]}'), /checks array/);
  assert.throws(() => parseReviewVerdict('{"verdict":"accepted","findings":[],"checks":[]}'), /summary/);
  assert.throws(() => parseReviewVerdict('[]'), /JSON object/);
  assert.throws(() => parseReviewVerdict('{"verdict":"accepted","findings":[],"checks":"all","summary":"s"}'), /checks array/);
  assert.throws(() => parseReviewVerdict('{"verdict":"accepted","findings":[{}],"checks":[],"summary":"s"}'), /nonempty issue/);
});

