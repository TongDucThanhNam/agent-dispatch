// The fake worker records every round: prompt, resumed session and pinned model.
function makeWorker(project, { sessionId = 'sess_fixture', response = 'Stage finished: version returns v2. node --check exit 0.', edit = true, missingReportRound = -1 } = {}) {
  const capturePath = path.join(project, '.zcode-dispatch', 'worker-capture.json');
  fs.writeFileSync(capturePath, '[]');
  const fixture = path.join(project, '.worker-fixture.mjs');
  const appJs = JSON.stringify(path.join(project, 'src', 'app.js'));
  fs.writeFileSync(fixture, `import fs from 'node:fs';
const [round, resume, session, prompt] = process.argv.slice(2);
const captures = JSON.parse(fs.readFileSync(${JSON.stringify(capturePath)}, 'utf8'));
captures.push({ round: Number(round), resume, session, promptChars: prompt.length, model: process.env.WORKER_MODEL, effort: process.env.WORKER_EFFORT });
fs.writeFileSync(${JSON.stringify(capturePath)}, JSON.stringify(captures));
if (${edit ? 'true' : 'false'}) fs.appendFileSync(${appJs}, '// v2 marker round ' + round + '\\n');
process.stdout.write(JSON.stringify({ sessionId: session, ...(Number(round) === ${missingReportRound} ? {} : {response: ${JSON.stringify(response)}}) }));
`);
  return {
    spawnWorker({ config, prompt, round, out, err }) {
      return spawn(process.execPath, [fixture, String(round), config.resumeSessionId ?? '', sessionId, prompt],
        { env: {...process.env, WORKER_MODEL: config.expectedModel, WORKER_EFFORT: config.zcodeEffort ?? config.agyEffort ?? ''}, shell: false, windowsHide: true, stdio: ['ignore', out, err] });
    },
    captures: () => JSON.parse(fs.readFileSync(capturePath, 'utf8'))
  };
}

function telemetryFactory(overrides = {}, usage = { modelCalls: 2, inputTokens: 100, outputTokens: 40, cacheReadTokens: 30, retries: 0 }) {
  return () => ({ read: () => ({ available: true, sessionId: overrides.sessionId ?? 'sess_fixture', model: overrides.model ?? null,
    provider: overrides.provider ?? null, lastActivityAt: Date.now(), errors: overrides.errors ?? [], tools: [], todos: [],
    ...(usage ? { usage } : {}) }), close() {} });
}

async function runLoop(t, name, { steps, maxAutoCorrections = 2, workerKind = 'zcode', extra = {}, worker: workerOptions = {}, telemetryFactory: customTelemetry } = {}) {
  const project = makeProject(t, name);
  const codexExe = writeReviewerFixture(project, steps);
  const launch = { workflowVersion: 1, project, promptFile: path.join(project, 'assignment.md'), runId: `loop-${name}`, workerKind, codexExe, threadId: UUID,
    pollMs: 100, quietMs: 500, stallMs: 2000, keepOpenMs: 0,
    maxAutoCorrections, reviewPaths: ['src'], objective: 'Deliver the v2 marker.', stageAcceptance: ['src/app.js version() returns v2'],
    preservedContracts: 'The export shape of src/app.js is a preserved contract.',
    remainingScope: 'Remaining scope: docs update and the final integration gate.', testEvidence: ['assignment.md'], ...extra };
  if (workerKind === 'agy') { launch.model = 'agy-fixture-model'; launch.effort = 'high'; }
  const config = validateConfig(launch);
  const worker = makeWorker(project, workerOptions);
  const callbacks = [];
  const deps = { spawnWorker: worker.spawnWorker,
    telemetryFactory: customTelemetry ?? telemetryFactory(workerKind === 'agy' ? { sessionId: UUID } : {}),
    runCallback: async (thread, message) => { callbacks.push({ thread, message }); return { ok: true, exitCode: 0 }; } };
  const state = await supervise(config, deps);
  return { project, config, state, callbacks, captures: worker.captures() };
}

