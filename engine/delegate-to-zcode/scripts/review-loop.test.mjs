  assert.equal(before.kind, 'paths');
  assert.ok(before.fingerprint);
  const limited = await computeSourceState(config, {maxFiles: 0});
  assert.equal(limited.complete, false);
  assert.equal(diffSourceStates(before, limited).comparable, false);
  fs.writeFileSync(path.join(project, 'src', 'app.js'), 'changed');
  const after = await computeSourceState(config);
  const diff = diffSourceStates(before, after);
  assert.equal(diff.comparable, true);
  assert.equal(diff.identical, false);
  assert.deepEqual(diff.changed, ['src/app.js']);
