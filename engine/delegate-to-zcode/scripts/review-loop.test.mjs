function makeProject(t, name, { source = true } = {}) {
  const project = path.join(root, `${name}-${process.pid}-${fixtureSeq++}`);
  fs.mkdirSync(path.join(project, '.zcode-dispatch'), { recursive: true });
  if (source) {
    fs.mkdirSync(path.join(project, 'src'), { recursive: true });
    fs.writeFileSync(path.join(project, 'src', 'app.js'), 'export const version = () => "v1";\n');
  }
  const promptFile = path.join(project, 'assignment.md');
  fs.writeFileSync(promptFile, 'Stage: bump the version marker to v2.\nStage acceptance: src/app.js exports version() returning "v2" and the worker ran node --check on it.\nScope: only src/app.js. Preserve the existing export shape.\nReturn boundary: finish and verify, then return for review.');
  t.after(() => { try { fs.rmSync(project, { recursive: true, force: true }); } catch {} });
  return project;
}

